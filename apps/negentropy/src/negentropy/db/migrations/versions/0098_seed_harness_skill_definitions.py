def _frontmatter(text: str) -> dict:
    """极简 frontmatter 解析（与 registry.parse_frontmatter 同义）；失败返回 {}。"""
    if not text.startswith("---"):
        return {}
    lines = text.splitlines()
    end = None
    for i in range(1, len(lines)):
        if lines[i].strip() in ("---", "..."):
            end = i
            break
    if end is None:
        return {}
    try:
        fm = yaml.safe_load("\n".join(lines[1:end])) or {}
    except yaml.YAMLError:
        return {}
    return fm if isinstance(fm, dict) else {}


def upgrade() -> None:
    bind = op.get_bind()
    stmt = sa.text(
        f"""
        INSERT INTO {SCHEMA}.definitions
            (kind, key, format, source, meta, version, checksum, owner_id, is_system, is_enabled, sort_order)
        VALUES ('harness_skill', :key, 'markdown', :source, :meta, :version, :checksum, 'system', TRUE, TRUE, :sort_order)
        ON CONFLICT (kind, key) DO NOTHING
        """
    ).bindparams(
        sa.bindparam("key", type_=sa.Text),
        sa.bindparam("source", type_=sa.Text),
        sa.bindparam("meta", type_=JSONB),
        sa.bindparam("version", type_=sa.Text),
        sa.bindparam("checksum", type_=sa.Text),
        sa.bindparam("sort_order", type_=sa.Integer),
    )

    for idx, b64 in enumerate(_SEED_B64):
        source = base64.b64decode(b64).decode("utf-8")
        fm = _frontmatter(source)
        name = str(fm.get("name") or "").strip()
        if not name:
            continue
        meta = {k: fm[k] for k in ("name", "description", "allowed-tools") if k in fm}
        checksum = hashlib.sha256(source.encode("utf-8")).hexdigest()
        bind.execute(
            stmt,
            {
                "key": name,
                "source": source,
                "meta": meta,
                "version": None,  # harness SKILL.md 无 version 字段
                "checksum": checksum,
                "sort_order": idx,
            },
        )


