  const shuffle = ease(clamp01(progress(frame, atShuffle, 20)));
  const settle = clamp01(progress(frame, atSettle, 14));
  const shuffleP = shuffle * (1 - settle);
  // 演进链计数：8 刻度亮 → 14→18→27 逐档跳格定格（离散，跳格窗随句长派生）
  const rulerP = clamp01(progress(frame, atRuler, 12));
  const stepPhase = clamp01(progress(frame, atSteps, stepsDur));
